STYLE = '''    <style>\n      .seo-footer { margin-top: 54px; padding-top: 24px; border-top: 1px solid var(--line); color: var(--muted); font-size: 14px; line-height: 1.65; }\n      .seo-footer h2 { margin: 0 0 14px; color: var(--muted); font-size: 18px; }\n      .seo-footer p { margin: 10px 0; }\n      .seo-footer a { color: var(--nav); }\n    </style>\n'''

def text(rx, s):
    m = re.search(rx, s, re.S|re.I)
    if not m: raise RuntimeError('Missing pattern: '+rx)
    return re.sub(r'<[^>]+>', '', re.sub(r'\s+', ' ', m.group(1))).strip()

for fn, cfg in PAGES.items():
    p = Path('docs') / fn
    s = p.read_text(encoding='utf-8')
    title = text(r'<title>(.*?)</title>', s)
    h1 = text(r'<h1[^>]*>(.*?)</h1>', s)
    canonical = text(r'<link\s+rel="canonical"\s+href="(.*?)"', s)
    desc = cfg['desc']

    s, n = re.subn(r'<meta\s+name="description"\s+content=".*?">', f'<meta name="description" content="{desc}">', s, count=1)
    if n != 1: raise RuntimeError(f'{fn}: description')
    s, n = re.subn(r'<meta\s+property="og:description"\s+content=".*?">', f'<meta property="og:description" content="{desc}">', s, count=1)
    if n != 1: raise RuntimeError(f'{fn}: og description')

    if 'article:modified_time' not in s:
        marker = f'<meta property="og:url" content="{canonical}">'
        s = s.replace(marker, marker + f'\n    <meta property="article:modified_time" content="{DATE}">', 1)

    tw_title = title.replace(' | Ola Española','')
    if 'name="twitter:title"' not in s:
        marker = '<meta name="twitter:card" content="summary">'
        s = s.replace(marker, marker + f'\n    <meta name="twitter:title" content="{tw_title}">\n    <meta name="twitter:description" content="{desc}">', 1)
    else:
        s = re.sub(r'<meta\s+name="twitter:description"\s+content=".*?">', f'<meta name="twitter:description" content="{desc}">', s, count=1)

    if '"@type": "Article"' not in s:
        schema = '    <script type="application/ld+json">\n' + json.dumps({
            '@context':'https://schema.org','@type':'Article','headline':h1,'description':desc,
            'mainEntityOfPage':canonical,'publisher':{'@type':'Organization','name':'Ola Española','url':'https://ola-espanola.github.io/'},
            'dateModified':DATE,'inLanguage':'ru'
        }, ensure_ascii=False, indent=2) + '\n    </script>\n'
        marker = '    <!-- structured:breadcrumbs -->'
        if marker not in s: raise RuntimeError(f'{fn}: breadcrumbs marker')
        s = s.replace(marker, schema + marker, 1)

    if 'class="seo-footer"' not in s:
        if '.seo-footer {' not in s:
            s = s.replace('  </head>', STYLE + '  </head>', 1)
        footer = f'''\n        <section class="seo-footer" aria-label="Дополнительная информация">\n          <h2>{cfg['footer_h']}</h2>\n          <p>{cfg['footer_p']}</p>\n        </section>\n'''
        pos = s.rfind('      </article>')
        if pos < 0: raise RuntimeError(f'{fn}: article close')
        s = s[:pos] + footer + s[pos:]

    p.write_text(s, encoding='utf-8')

print('Updated', len(PAGES), 'guide pages')
